// Optional browser regression check: requires playwright-core and Chromium.
// NODE_PATH=/workspace/.cloud-tools/calcolatore-pmi/node_modules node tests/rilievo.web.cjs
const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(process.env.APP_URL || 'http://localhost:8081/calcolatore-pmi/', { waitUntil: 'networkidle' });
    const data = page.getByRole('textbox', { name: 'Data rilievo *', exact: true });
    const ora = page.getByRole('textbox', { name: 'Ora rilievo *', exact: true });
    await data.waitFor({ timeout: 5000 });
    assert.equal(await page.getByText('Limiti al 95%:', { exact: false }).count(), 0);
    await data.fill('31/04/2026');
    await ora.fill('06:00');
    assert.equal(await page.getByText('Limiti al 95%:', { exact: false }).count(), 0);
    await data.fill('28/10/2026');
    await ora.fill('24:00');
    assert.equal(await page.getByText('Limiti al 95%:', { exact: false }).count(), 0);
    await ora.fill('06:00');
    await page.getByText('9 h 41 min ± 2,8 h', { exact: true }).waitFor();
    await page.getByText('tra il 27/10/2026 alle 17:31 e il 27/10/2026 alle 23:07', { exact: true }).waitFor();
    await page.getByRole('button', { name: /Metodo composto/ }).click();
    await page.getByText('Confronto degli intervalli', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Rigidità cadaverica: Assente', exact: true }).click();
    await page.getByText('Entro 7,0 h', { exact: true }).first().waitFor();
    await page.getByText('Sovrapposizione comune: 6,9–7,0 h', { exact: true }).waitFor();
    await page.getByText('Confronto degli intervalli', { exact: true }).locator('..').screenshot({ path: '/tmp/pmi-intervalli-mobile.png' });
    await page.getByRole('button', { name: 'Fenomeno di Zsako: Presente', exact: true }).click();
    await page.getByText('Nessuna sovrapposizione comune', { exact: true }).waitFor();
    assert.equal(await page.getByText('Sovrapposizione comune: 6,9–7,0 h', { exact: true }).count(), 0);
    await page.getByRole('button', { name: /Testo per il verbale/ }).click();
    assert.match(await page.locator('body').innerText(), /Il 28\/10\/2026 alle ore 06:00/);
    await page.getByRole('button', { name: 'Fenomeno di Zsako: Presente', exact: true }).click();
    await page.getByRole('button', { name: 'Rigidità cadaverica: In risoluzione', exact: true }).click();
    await page.getByRole('textbox', { name: 'Rettale', exact: true }).fill('15');
    await page.getByText('Limiti termici non disponibili: confronto dei soli reperti selezionati.', { exact: true }).waitFor();
    await page.getByText('Sovrapposizione comune: Almeno 24,0 h', { exact: true }).waitFor();
    await page.getByText('non oltre il 27/10/2026 alle 06:00', { exact: true }).first().waitFor();
    await page.getByRole('button', { name: 'Rigidità cadaverica: In risoluzione', exact: true }).click();
    await page.getByText('Seleziona i reperti rilevati per confrontare i loro intervalli.', { exact: true }).waitFor();
    await page.getByRole('textbox', { name: 'Rettale', exact: true }).fill('30');
    await page.getByText('Temperatura ambiente incerta? Inserisci un intervallo', { exact: true }).click();
    await page.getByText('Intervallo esteso:', { exact: false }).waitFor();
    await page.getByText(/^Henssge: /).waitFor();
    await page.getByRole('textbox', { name: 'Ambiente min', exact: true }).fill('18');
    await page.getByRole('textbox', { name: 'Ambiente max', exact: true }).fill('12');
    await page.getByText('Limiti termici non disponibili: confronto dei soli reperti selezionati.', { exact: true }).waitFor();
    assert.match(await page.locator('body').innerText(), /Con temperatura ambiente incerta non è disponibile un intervallo termico/);
    assert.equal(await page.getByText(/^Henssge: /).count(), 0);
    await page.getByText('Usa un valore unico di temperatura ambiente', { exact: true }).click();
    await page.getByRole('button', { name: 'Rigidità cadaverica: Assente', exact: true }).click();
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.getByText('Confronto degli intervalli', { exact: true }).locator('..').screenshot({ path: '/tmp/pmi-intervalli-desktop.png' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByText('Esercizi', { exact: true }).first().click();
    await page.getByText('Calcolo', { exact: true }).click();
    assert.equal(await data.inputValue(), '28/10/2026');
    await data.fill('');
    assert.equal(await page.getByText('Limiti al 95%:', { exact: false }).count(), 0);
    assert.equal(await page.getByText('Confronto degli intervalli', { exact: true }).count(), 0);
    assert.equal(await page.getByText('Copia', { exact: true }).count(), 0);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('Browser mobile: obbligatorietà, calendario, intervalli, grafico, incompatibilità, verbale e navigazione OK');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
